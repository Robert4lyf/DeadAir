// Builds dead-air.html: the whole game in one file that opens directly from disk (file://),
// with scripts bundled, styles inlined and artwork embedded as data URIs.
// Usage: npm run build:standalone
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..'),
  dist = path.join(root, 'dist'),
  out = path.join(root, 'dead-air.html');

const bundle = execFileSync(
  'npx',
  ['-y', 'esbuild@0.24.2', 'dist/game.js', '--bundle', '--format=iife', '--legal-comments=none'],
  { cwd: root, encoding: 'utf8', maxBuffer: 1 << 26 },
);

const art = {};
for (const file of fs.readdirSync(path.join(dist, 'art')).sort()) {
  if (!file.endsWith('.webp')) continue;
  const data = fs.readFileSync(path.join(dist, 'art', file)).toString('base64');
  art[path.basename(file, '.webp')] = `data:image/webp;base64,${data}`;
}

// Inline scripts must not contain a closing script tag or an HTML comment opener.
const safe = (code) => code.replaceAll('</script', '<\\/script').replaceAll('<!--', '<\\!--');
const css = fs.readFileSync(path.join(dist, 'style.css'), 'utf8');
let html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');

const replace = (from, to) => {
  if (!html.includes(from)) throw new Error(`build-standalone: expected to find ${from}`);
  html = html.replace(from, () => to);
};
replace('<link rel="stylesheet" href="style.css" />', `<style>\n${css}</style>`);
replace(
  '<script type="module" src="game.js"></script>',
  `<script>window.DEAD_AIR_ART = ${JSON.stringify(art)};</script>\n<script>\n${safe(bundle)}</script>`,
);
replace('<a href="./"', '<a href=""');
replace(
  '<!doctype html>',
  '<!doctype html>\n<!-- Generated by `npm run build:standalone` from dist/. Do not edit by hand. -->',
);

fs.writeFileSync(out, html);
console.log(`Wrote ${path.relative(root, out)} (${(html.length / 1048576).toFixed(1)} MB)`);
